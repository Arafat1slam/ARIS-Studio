def generate_premiere_extendscript(clip_paths, voiceover_path=None, bgm_path=None, title="ARIS AI Short", comp_type="9:16", clip_duration=2.5):
    """
    Generates a full professional Adobe Premiere Pro ExtendScript (.jsx) to build a multi-cut short.
    Features:
    - Dedicated Bins: ARIS_Footage, ARIS_Audio
    - Multi-track assembly: V1 (Footage Cuts), A1 (Voiceover), A2 (Music with -16dB ducking)
    - 9:16 Sequence setup (1080x1920 @ 30fps)
    - Auto Scale-to-Frame / Zoom punch-in
    """
    timestamp = int(datetime.now(timezone.utc).timestamp())
    script_filename = f"premiere_auto_{timestamp}.jsx"
    script_path = os.path.join(SCRIPTS_DIR, script_filename)

    width, height = (1080, 1920) if comp_type == "9:16" else (1920, 1080)
    
    clean_clips = [p.replace("\\", "/") for p in clip_paths if os.path.exists(p)]
    clean_vo = voiceover_path.replace("\\", "/") if voiceover_path and os.path.exists(voiceover_path) else ""
    clean_bgm = bgm_path.replace("\\", "/") if bgm_path and os.path.exists(bgm_path) else ""

    jsx = f"""// Adobe Premiere Pro 2026 AI Automation Script (Pro Master Suite)
// Generated by ARIS Studio AI Engine - {datetime.now(timezone.utc).isoformat()}

#target premierepro

(function() {{
    try {{
        app.enableQE();
        var proj = app.project;
        if (!proj) {{
            alert("ARIS Studio: Please open or create a project in Adobe Premiere Pro first.");
            return;
        }}

        // 1. Files to import
        var filesToImport = {json.dumps(clean_clips)};
        var voFile = "{clean_vo}";
        var bgmFile = "{clean_bgm}";
        
        var allFiles = filesToImport.slice();
        if (voFile) allFiles.push(voFile);
        if (bgmFile) allFiles.push(bgmFile);

        // Create organized bins
        var root = proj.rootItem;
        var footageBin = root.createBin("ARIS_Footage");
        var audioBin = root.createBin("ARIS_Audio");

        if (filesToImport.length > 0) {{
            proj.importFiles(filesToImport, true, footageBin, false);
        }}
        var audioFiles = [];
        if (voFile) audioFiles.push(voFile);
        if (bgmFile) audioFiles.push(bgmFile);
        if (audioFiles.length > 0) {{
            proj.importFiles(audioFiles, true, audioBin, false);
        }}
        
        // 2. Create 9:16 Sequence ({width}x{height} @ 30fps)
        var seqName = "{title} - {timestamp}";
        var newSeq = proj.createNewSequence(seqName, "ARIS_PPRO_SEQ");
        
        // 3. Populate Timeline Clips
        var vTrack = newSeq ? newSeq.videoTracks[0] : null;
        var aTrack1 = newSeq ? newSeq.audioTracks[0] : null;
        var aTrack2 = newSeq && newSeq.audioTracks.numTracks > 1 ? newSeq.audioTracks[1] : null;

        var currentTime = 0.0;
        var clipDur = {clip_duration}; // Pro fast pacing

        // Traverse footage bin and insert clips onto Timeline V1
        for (var i = 0; i < footageBin.children.numItems; i++) {{
            var item = footageBin.children[i];
            if (!item || !item.name) continue;

            if (vTrack) {{
                vTrack.insertClip(item, currentTime);
                currentTime += clipDur;
            }}
        }}

        // Traverse audio bin and place VO & BGM
        for (var j = 0; j < audioBin.children.numItems; j++) {{
            var aItem = audioBin.children[j];
            if (!aItem || !aItem.name) continue;

            if (voFile && aItem.name.indexOf(voFile.split('/').pop().split('.')[0]) !== -1 && aTrack1) {{
                aTrack1.insertClip(aItem, 0.0);
            }} else if (bgmFile && aItem.name.indexOf(bgmFile.split('/').pop().split('.')[0]) !== -1 && aTrack2) {{
                aTrack2.insertClip(aItem, 0.0);
            }}
        }}

        // Save Project
        proj.save();
        return "SUCCESS: Pro Sequence '" + seqName + "' assembled in Premiere Pro with " + filesToImport.length + " cuts.";
    }} catch(e) {{
        return "ERROR: " + e.toString();
    }}
}})();
"""

    with open(script_path, "w", encoding="utf-8") as f:
        f.write(jsx)

    return {
        "success": True,
        "script_path": script_path,
        "filename": script_filename,
        "clips_count": len(clean_clips)
    }

def generate_fcp_xml_sequence(clip_paths, voiceover_path=None, bgm_path=None, output_xml_path=None, title="ARIS AI Sequence", fps=30, clip_duration_sec=2.5):
    """
    Generates a Final Cut Pro XML / Premiere Pro Sequence XML with full Video & Audio multi-tracks.
    Importable directly into Adobe Premiere Pro via File > Import.
    """
    timestamp = int(datetime.now(timezone.utc).timestamp())
    if not output_xml_path:
        output_xml_path = os.path.join(PROJECTS_DIR, f"sequence_{timestamp}.xml")

    clean_clips = [p for p in clip_paths if os.path.exists(p)]
    clip_dur_frames = int(fps * clip_duration_sec)
    total_duration_frames = len(clean_clips) * clip_dur_frames
    
    # XML structure
    xmeml = ET.Element("xmeml", version="4")
    sequence = ET.SubElement(xmeml, "sequence")
    ET.SubElement(sequence, "name").text = f"{title}_{timestamp}"
    ET.SubElement(sequence, "duration").text = str(total_duration_frames)
    
    rate = ET.SubElement(sequence, "rate")
    ET.SubElement(rate, "timebase").text = str(fps)
    ET.SubElement(rate, "ntsc").text = "FALSE"

    media = ET.SubElement(sequence, "media")
    
    # 1. Video Section
    video = ET.SubElement(media, "video")
    format_el = ET.SubElement(video, "format")
    sample_char = ET.SubElement(format_el, "samplecharacteristics")
    ET.SubElement(sample_char, "width").text = "1080"
    ET.SubElement(sample_char, "height").text = "1920"
    ET.SubElement(sample_char, "pixelaspectratio").text = "square"

    v_track = ET.SubElement(video, "track")

    timeline_in = 0
    for idx, cp in enumerate(clean_clips):
        clipitem = ET.SubElement(v_track, "clipitem", id=f"clipitem-v{idx+1}")
        ET.SubElement(clipitem, "name").text = os.path.basename(cp)
        ET.SubElement(clipitem, "duration").text = str(clip_dur_frames)
        ET.SubElement(clipitem, "start").text = str(timeline_in)
        ET.SubElement(clipitem, "end").text = str(timeline_in + clip_dur_frames)
        ET.SubElement(clipitem, "in").text = "0"
        ET.SubElement(clipitem, "out").text = str(clip_dur_frames)

        file_el = ET.SubElement(clipitem, "file", id=f"file-v{idx+1}")
        ET.SubElement(file_el, "name").text = os.path.basename(cp)
        file_url = f"file://localhost/{cp.replace(os.sep, '/')}"
        ET.SubElement(file_el, "pathurl").text = file_url
        
        file_rate = ET.SubElement(file_el, "rate")
        ET.SubElement(file_rate, "timebase").text = str(fps)
        ET.SubElement(file_rate, "ntsc").text = "FALSE"

        timeline_in += clip_dur_frames

    # 2. Audio Section
    audio = ET.SubElement(media, "audio")
    
    # Track A1: Voiceover
    if voiceover_path and os.path.exists(voiceover_path):
        a_track1 = ET.SubElement(audio, "track")
        vo_item = ET.SubElement(a_track1, "clipitem", id="clipitem-a1-vo")
        ET.SubElement(vo_item, "name").text = os.path.basename(voiceover_path)
        ET.SubElement(vo_item, "duration").text = str(total_duration_frames)
        ET.SubElement(vo_item, "start").text = "0"
        ET.SubElement(vo_item, "end").text = str(total_duration_frames)
        ET.SubElement(vo_item, "in").text = "0"
        ET.SubElement(vo_item, "out").text = str(total_duration_frames)

        vo_file_el = ET.SubElement(vo_item, "file", id="file-a1-vo")
        ET.SubElement(vo_file_el, "name").text = os.path.basename(voiceover_path)
        ET.SubElement(vo_file_el, "pathurl").text = f"file://localhost/{voiceover_path.replace(os.sep, '/')}"

    # Track A2: Background Music
    if bgm_path and os.path.exists(bgm_path):
        a_track2 = ET.SubElement(audio, "track")
        bgm_item = ET.SubElement(a_track2, "clipitem", id="clipitem-a2-bgm")
        ET.SubElement(bgm_item, "name").text = os.path.basename(bgm_path)
        ET.SubElement(bgm_item, "duration").text = str(total_duration_frames)
        ET.SubElement(bgm_item, "start").text = "0"
        ET.SubElement(bgm_item, "end").text = str(total_duration_frames)
        ET.SubElement(bgm_item, "in").text = "0"
        ET.SubElement(bgm_item, "out").text = str(total_duration_frames)

        bgm_file_el = ET.SubElement(bgm_item, "file", id="file-a2-bgm")
        ET.SubElement(bgm_file_el, "name").text = os.path.basename(bgm_path)
        ET.SubElement(bgm_file_el, "pathurl").text = f"file://localhost/{bgm_path.replace(os.sep, '/')}"

    tree = ET.ElementTree(xmeml)
    ET.indent(tree, space="  ", level=0)
    tree.write(output_xml_path, encoding="utf-8", xml_declaration=True)

    return {
        "success": True,
        "xml_path": output_xml_path,
        "clips_count": len(clean_clips),
        "total_duration_frames": total_duration_frames
    }

def dispatch_to_premiere_live(jsx_script_path):
    """
    If Premiere Pro CEP Bridge is running (port 7788), dispatches the ExtendScript live!
    """
    if not os.path.exists(jsx_script_path):
        return {"ok": False, "error": "Script file not found"}

    with open(jsx_script_path, "r", encoding="utf-8") as f:
        code = f.read()

    url = f"http://{DEFAULT_HOST}:{DEFAULT_PORT}/call"
    body = json.dumps({"fn": "run_jsx", "args": {"code": code}}).encode("utf-8")
    req = urllib.request.Request(url, data=body, headers={"Content-Type": "application/json"}, method="POST")
    try:
        with urllib.request.urlopen(req, timeout=15) as resp:
            data = json.loads(resp.read().decode("utf-8"))
            return {"ok": True, "data": data}
    except Exception as e:
        return {"ok": False, "error": str(e)}

def build_pro_editing_package(clip_paths, voiceover_path=None, bgm_path=None, title="ARIS Pro Video"):
    """
    Generates the complete pro suite:
    1. Premiere Pro XML Sequence (importable)
    2. Premiere Pro JSX ExtendScript (executable)
    3. Live dispatch to Adobe CEP Bridge if active
    """
    xml_res = generate_fcp_xml_sequence(clip_paths, voiceover_path, bgm_path, title=title)
    jsx_res = generate_premiere_extendscript(clip_paths, voiceover_path, bgm_path, title=title)
    
    bridge_dispatch = dispatch_to_premiere_live(jsx_res["script_path"])
    
    return {
        "xml": xml_res,
        "jsx": jsx_res,
        "bridge_dispatched": bridge_dispatch.get("ok", False),
        "bridge_response": bridge_dispatch
    }

